/// Core of (identical arithmetic): single precision sine of `x`using `t` for the data the original reads from memory.
pub fn sinf_with(x: f32, t: &SinTables) -> f32 {
    let bits = x.to_bits();
    let abs = bits & 0x7fff_ffff;
    // r8d = 0x49ffffff - abs; r10d = abs - 0x39800000; jl when (r8d | r10d) is negative as i32
    let r8 = MAIN_MAX_BITS.wrapping_sub(abs);
    let r10 = abs.wrapping_sub(MAIN_MIN_BITS);
    let xd = x as f64;
    let n: u32;
    let g: f64;
    if ((r8 | r10) as i32) < 0 {
        // tiny, big, or non finite
        if abs <= TINY_LIMIT_BITS {
            // cvtss2sd; mulsd [tiny scale]; cvtsd2ss
            return (xd * t.tiny_scale) as f32;
        }
        if (bits & 0x7f80_0000) == 0x7f80_0000 {
            // Inf or NaN: subss xmm0, xmm0
            return x - x;
        }
        // big finite argument, exponent group table lookup
        let grp = ((((r10 >> 23).wrapping_sub(0x1b)) & 0xfff8) >> 3) as usize; // byte offset is 16 * grp
        let e = t.big[grp];
        let hi = f64::from_bits(e[0] & 0xffff_ffff_ff00_0000);
        let mid = f64::from_bits(e[0] << 40);
        let lo = f64::from_bits(e[1]);
        let hx = hi * xd;
        let mx = mid * xd;
        let xlo = xd * lo;
        let s = hx + mx;
        let e1 = hx - s;
        let s2 = s + MAGIC;
        let err = mx + e1;
        n = (s2.to_bits() & 0xffff_ffff) as u32;
        let nd = s2 - MAGIC;
        let f = s - nd;
        g = (xlo + err) + f;
    } else {
        // main path, one multiply by 128/pi with a split constant
        let tt = K_128_OVER_PI * xd;
        let s2 = tt + MAGIC;
        n = (s2.to_bits() & 0xffff_ffff) as u32;
        let nd = s2 - MAGIC;
        let xc = xd * C_LOW;
        let f = tt - nd;
        g = xc + f;
    }
    // sector fold and polynomial
    let n2 = n.wrapping_add(n);
    let b = n2 as u8;
    let m = ((b as i8) >> 7) as u8;
    let babs = b.wrapping_add(m) ^ m; // abs of the signed byte (0x80 stays 0x80)
    let idx = (babs & 0xfe) as usize; // even, 0..=128; byte offset is idx * 8
    let eax = n2 & 0x180;
    let s_a = (((eax + 0x80) & 0x100) as u64) << 0x37; // sign of the A term (bit 63)
    let s_b = ((eax & 0x100) as u64) << 0x37; // sign of the B term
    let ent = t.main[idx >> 1];
    let a = f64::from_bits(ent[0]);
    let bb = f64::from_bits(ent[1]);
    let g2 = g * g;
    let p_cos = (K1 - g2) * bb;
    let p_sin_poly = f64::from_bits((K2 - g2).to_bits() ^ s_a);
    let p_sin = (a * g) * p_sin_poly;
    let r = f64::from_bits(p_cos.to_bits() ^ s_b) + p_sin;
    r as f32
}

///  (route of the AVX body; selected when the low byte of the feature word is 0xff). Tables read by the original: big, main, tiny scale .
pub fn sinf_1_with(x: f32, t: &SinTables) -> f32 {
    sinf_with(x, t)
}

///  (SSE2 variant, selected when bit 0 of the feature word is set): same arithmetic as; tables big, main, tiny scale .
pub fn sinf_2_with(x: f32, t: &SinTables) -> f32 {
    sinf_with(x, t)
}

///  with the assumed tables.
pub fn sinf_1(x: f32) -> f32 {
    sinf_with(x, &SinTables::assumed())
}

///  with the assumed tables (assumes the second table copy equals the first).
pub fn sinf_2(x: f32) -> f32 {
    sinf_with(x, &SinTables::assumed())
}

/// the CPU dispatcher. `feature` is the 64 bit word the GOT slot points to; `t_cc_cell_a` and `t_cee_cell_a` are the table copies of the
/// two targets. Returns None for the path that calls the CPU init and retries (low byte != 0xff and bit 0 clear): the original does not
/// terminate there without the real init.
pub fn sinf_3_with(x: f32, feature: u64, t_cc_cell_a: &SinTables, t_cee_cell_a: &SinTables) -> Option<f32> {
    if feature & 0xff == 0xff {
        Some(sinf_1_with(x, t_cc_cell_a))
    } else if feature & 1 != 0 {
        Some(sinf_2_with(x, t_cee_cell_a))
    } else {
        None
    }
}

///  with the assumed tables for both targets.
pub fn sinf_3(x: f32, feature: u64) -> Option<f32> {
    let t = SinTables::assumed();
    sinf_3_with(x, feature, &t, &t)
}

/// The function the AVX route (feature word 0x9d97ff) computes: resolved to .
pub fn s_sin(x: f32) -> f32 {
    sinf_1(x)
}
