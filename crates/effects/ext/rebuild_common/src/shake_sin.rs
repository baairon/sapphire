//! The tables are ASSUMED (NOT_CAPTURED), see the doc comments below.
//!
//! math: the float math chain behind (dump file offsets; VA = offset for code, data addresses below are VAs).
//!
//! What the chain is (INFERRED from the instructions, constants K1 K2 C verified MEASURED against exact 128/pi and pi^2, see spec/math_notes.md):
//! a single precision SINE, `sinf`computed in double precision. is a CPU dispatcher (feature word at the pointer in GOT slot):
//! low byte 0xff selects (the route of the AVX body, whose feature word is 0x9d97ff), else bit 0 selects (SSE2 variant,
//! identical arithmetic, tables bytes higher), else it calls the CPU init and retries (never terminates without the real init).
//!
//! Constants in the code (immediates) are exact. Constants in data (three tables per variant) are NOT_CAPTURED: they are the single labelled
//! assumption of this module, [`SinTables::assumed`], generated by `tools/math_tables.py`, overridable by building your own [`SinTables`].
//! Rounding mode: the original forces round-to-nearest for the arithmetic and restores the caller's mode before the final double to float
//! conversion; here everything is round-to-nearest (the default MXCSR). NaN rule: plain Rust arithmetic (`x - x`), as decided by the owner.

/// 1.5 * 2^52, the round-to-integer magic number (immediate).
pub const MAGIC: f64 = f64::from_bits(0x4338_0000_0000_0000);
/// 128/pi rounded to 24 bits (immediate).
pub const K_128_OVER_PI: f64 = f64::from_bits(0x4044_5f30_6e00_0000);
/// RN(128/pi - K_128_OVER_PI) (immediate, MEASURED equal to the exact value rounded).
pub const C_LOW: f64 = f64::from_bits(0xbe5b_1bbe_ad60_3d8b);
/// RN(32768/pi^2) = 2/(pi/128)^2, cos polynomial constant (immediate).
pub const K1: f64 = f64::from_bits(0x40a9_f02f_6222_c720);
/// RN(98304/pi^2) = 6/(pi/128)^2, sin polynomial constant (immediate).
pub const K2: f64 = f64::from_bits(0x40c3_7423_899a_1558);

/// Lower bound of the main path: |x| bits >= this (0x39800000 = 2^-12), compare .
pub const MAIN_MIN_BITS: u32 = 0x3980_0000;
/// Upper bound of the main path: |x| bits <= this (just below 2^21), compare .
pub const MAIN_MAX_BITS: u32 = 0x49ff_ffff;
/// Tiny path limit (cmp): |x| bits <= this uses the scale multiply; above it (and not Inf/NaN) the big argument path.
pub const TINY_LIMIT_BITS: u32 = 0x3e00_0000;

/// The data the original reads from NOT_CAPTURED addresses. One value per variant is assumed identical (the second copy is a copy at).
#[derive(Clone, Debug)]
pub struct SinTables {
    /// Exponent group table (15 x 2 u64): word 0 = hi (top 40 bits) with mid in the low 24 bits, word 1 = lo as an f64 pattern.
    pub big: [[u64; 2]; 15],
    /// Sector table (65 x 2 u64): word 0 = A_k, word 1 = B_k as f64 patterns.
    pub main: [[u64; 2]; 65],
    /// Multiplier of the tiny path (|x| < 2^-12): result = (double)x * tiny_scale .
    pub tiny_scale: f64,
}

impl SinTables {
    /// ASSUMED reconstruction (INFERRED, not captured): B_k = sin(k pi/128)/K1, A_k = cos(k pi/128) (pi/128)/K2, big table = (128/pi) mod 2^(16-8G)
    /// split 29 + 13 + rest bits, tiny scale 1.0. Replace by the real bytes when they are captured.
    pub fn assumed() -> SinTables {
        SinTables { big: ASSUMED_BIG, main: ASSUMED_MAIN, tiny_scale: ASSUMED_TINY_SCALE }
    }
}

/// ASSUMED (NOT_CAPTURED): the tiny path multiplier. Any value within about 2^-30 of 1.0 gives the same float results.
pub const ASSUMED_TINY_SCALE: f64 = 1.0;

