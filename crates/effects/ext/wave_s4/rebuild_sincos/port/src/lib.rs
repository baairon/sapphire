/// Which route a call took (for coverage reports and mutation tests).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Route {
    Fast,
    Tiny,
    NonFinite,
    DoubleMid,
    DoubleCw,
    DoublePh,
}

#[derive(Clone, Debug)]
pub struct Trace {
    pub route: Route,
    /// sincosf table entries read (lane 0, lane 1)
    pub s_idx: Option<(usize, usize)>,
    /// double table entry read by 
    pub d_idx: Option<usize>,
    /// quadrant returned by the reducer
    pub quad: Option<u32>,
    /// limb table base index of the Payne-Hanek step
    pub ph_rdi: Option<usize>,
}

fn tr(route: Route) -> Trace {
    Trace { route, s_idx: None, d_idx: None, quad: None, ph_rdi: None }
}

/// cvtss2si (round to nearest even, 0x80000000 when out of range or NaN)
fn cvtss2si(x: f32) -> i32 {
    if x.is_nan() || x >= 2147483648.0 || x < -2147483648.0 {
        i32::MIN
    } else {
        x.round_ties_even() as i32
    }
}

/// cvtsd2si 32 bit
fn cvtsd2si(x: f64) -> i32 {
    if x.is_nan() || x >= 2147483648.0 || x < -2147483648.0 {
        i32::MIN
    } else {
        x.round_ties_even() as i32
    }
}

fn nan_x0(x: f32) -> f32 {
    // mulss x, 0.0 on silicon: a NaN first operand comes back quieted, inf * 0 gives the default NaN
    if x.is_nan() {
        f32::from_bits(x.to_bits() | 0x0040_0000)
    } else {
        f32::from_bits(0xffc0_0000)
    }
}

/// (sin x, cos x) as the original computes them, plus the route taken.
pub fn sincosf_traced(x: f32) -> (f32, f32, Trace) {
    let bits = x.to_bits();
    let ax = (((bits >> 16) & 0x7fff) as u16).wrapping_sub(0x80);
    if ax <= 0x457f {
        return fast(x, bits);
    }
    if (ax as i16) <= 0x457f {
        // zero and denormal
        let xd = x as f64;
        let s = (xd * TINY_K) as f32;
        let c = (ONE - xd * xd) as f32;
        return (s, c, tr(Route::Tiny));
    }
    if (bits & 0x7f80_0000) == 0x7f80_0000 {
        let v = nan_x0(x);
        return (v, v, tr(Route::NonFinite));
    }
    let (s, c, t) = sincos_d(x as f64);
    (s as f32, c as f32, t)
}

pub fn sincosf_x(x: f32) -> (f32, f32) {
    let (s, c, _) = sincosf_traced(x);
    (s, c)
}

fn fast(x: f32, bits: u32) -> (f32, f32, Trace) {
    let tb = tables();
    let t = K1 * x;
    let edx = cvtss2si(t);
    let rt = (t + SHIFTER32) - SHIFTER32;
    let xd = x as f64;
    let m = (bits as u64) & SIGN32_MASK;
    let sg = (m << 32) ^ (m << 29);
    let a = f(A_HI ^ sg);
    let b = f(B_LO ^ sg);
    let rd = f((rt.to_bits() as u64) << 29);
    let i0 = (((edx as u32).wrapping_add(0x1c7600) << 4) as u64 & 0x3f0) as usize >> 4;
    let i1 = (((edx as u32).wrapping_add(0x1c7610) << 4) as u64 & 0x3f0) as usize >> 4;
    let r = xd - a * rd;
    let w = b * rd + r;
    let r2 = r * r;
    let p = (C_COS2 * r2 + ONE) + C_COS4 * (r2 * r2);
    let q = (C_SIN2 * r2 + ONE) + C_SIN4 * (r2 * r2);
    let e0 = tb.s[i0];
    let e1 = tb.s[i1];
    // lane 0: table sin at k, table cos at k; lane 1: table sin at k + 16, table cos at k + 16
    let o0 = f(e0[0]) * p + (w * f(e0[1])) * q;
    let o1 = f(e1[0]) * p + (w * f(e1[1])) * q;
    let mut trc = tr(Route::Fast);
    trc.s_idx = Some((i0, i1));
    (o0 as f32, o1 as f32, trc)
}

fn mul2(a: [f64; 2], b: [f64; 2]) -> [f64; 2] {
    [a[0] * b[0], a[1] * b[1]]
}
fn add2(a: [f64; 2], b: [f64; 2]) -> [f64; 2] {
    [a[0] + b[0], a[1] + b[1]]
}
fn sub2(a: [f64; 2], b: [f64; 2]) -> [f64; 2] {
    [a[0] - b[0], a[1] - b[1]]
}
fn c2(c: [u64; 2]) -> [f64; 2] {
    [f(c[0]), f(c[1])]
}
fn sp(v: f64) -> [f64; 2] {
    [v, v]
}

///  for finite arguments inside the f32 range |x| >= 8192 (the tiny branch of the original is not reachable from an f32).
/// Returns (sin, cos) as doubles.
pub fn sincos_d(x: f64) -> (f64, f64, Trace) {
    let hi16 = ((x.to_bits() >> 48) & 0x7fff) as u16;
    let ax = hi16.wrapping_sub(0x3030);
    if ax <= 0x10c5 {
        let (s, c, idx) = core_d(x, None);
        let mut t = tr(Route::DoubleMid);
        t.d_idx = Some(idx);
        return (s, c, t);
    }
    // large (the tiny and inf/NaN branches cannot be reached from the f32 wrapper; inf/NaN would return x * 0)
    let e = ((x.to_bits() >> 48) & 0x7ff0) as u16;
    if e == 0x7ff0 {
        let v = x * 0.0;
        return (v, v, tr(Route::NonFinite));
    }
    let (yh, yl, q, small, rdi) = reduce_x(x);
    let (s, c, idx) = core_d(yh, Some((yl, q)));
    let mut t = tr(if small { Route::DoubleCw } else { Route::DoublePh });
    t.d_idx = Some(idx);
    t.quad = Some(q);
    t.ph_rdi = rdi;
    (s, c, t)
}

/// The table walk shared by the mid and large routes of (and).
fn core_d(x: f64, red: Option<(f64, u32)>) -> (f64, f64, usize) {
    let tb = tables();
    let t = KD * x;
    let edx = cvtsd2si(t);
    let n = (t + SHD) - SHD;
    let p1n = DP1 * n;
    let q16 = match red {
        Some((_, q)) => (q as u64) << 4,
        None => 0,
    };
    let idx = ((edx as u32 as u64 + 0x1c7600 + q16) & 0x3f) as usize;
    let e = &tb.d[idx];
    let p0 = [f(e[0]), f(e[1])];
    let p1 = [f(e[2]), f(e[3])];
    let p2 = [f(e[4]), f(e[5])];
    let p3 = [f(e[6]), f(e[7])];
    let p2n = DP2 * n;
    let x1 = x - p1n;
    let p3n = n * DP3;
    let r1 = x1 - p2n;
    let mut s5 = mul2(c2(C_CELL_E), sp(x1));
    let mut a7 = mul2(p1, sp(r1));
    let mut e3 = x1 - r1;
    s5 = mul2(s5, sp(r1));
    let r2 = r1 * r1;
    e3 -= p2n;
    let mut m1 = p3n - e3;
    let aa = add2(p0, p3);
    a7 = sub2(a7, aa);
    if let Some((ylo, _)) = red {
        m1 -= ylo;
    }
    let m1v = mul2(sp(m1), a7);
    let hi7 = p1;
    let a2 = mul2(aa, sp(r1));
    let mut s6 = mul2(c2(C_CELL_D), sp(r2));
    let a3 = mul2(p3, sp(r1));
    let a2 = mul2(a2, sp(r2));
    let hi7 = mul2(hi7, sp(r2));
    let r4 = r2 * r2;
    s5 = add2(s5, c2(C_CELL_C));
    let a4 = mul2(sp(r1), p0);
    s6 = add2(s6, c2(C_CELL_B));
    s5 = mul2(s5, sp(r4));
    let a0 = a3;
    let a3b = add2(a3, p1);
    s6 = add2(s6, s5);
    let t6 = mul2(sp(s6[1]), hi7);
    let t2 = mul2(a2, sp(s6[0]));
    let a7b = a4;
    let a4b = add2(a4, a3b);
    let a5 = sub2(p1, a3b);
    let a3c = sub2(a3b, a4b);
    let mut m = add2(m1v, p2);
    let a5 = add2(a5, a0);
    let a3d = add2(a3c, a7b);
    m = add2(m, a5);
    m = add2(m, a3d);
    m = add2(m, t2);
    m = add2(m, t6);
    m = add2(m, a4b);
    (m[0], m[1], idx)
}

/// reduce |x| to (hi, lo) about a multiple of pi/4 with the sign applied, plus the quadrant.
/// Returns (hi, lo, quadrant, cody_waite_route, ph_table_base).
fn reduce_x(xin: f64) -> (f64, f64, u32, bool, Option<usize>) {
    let bits = xin.to_bits();
    let r8 = (bits >> 63) as u32;
    let a_bits = bits & !(1u64 << 63);
    let a = f(a_bits);
    let edx = ((a_bits >> 52) & 0x7ff) as u32;
    if edx >= 0x41d {
        let (h, l, q, rdi) = reduce_ph(a_bits, edx, r8);
        return (h, l, q, false, Some(rdi));
    }
    let tt = FOUR_OVER_PI * a;
    let tb = tt.to_bits();
    let ecx = ((tb >> 52) & 0x7ff) as u32;
    let esi: u32 = if ecx >= 0x3ff {
        let hi = (tb >> 32) as u32;
        let lo = tb as u32;
        let cl = 0x1eu32.wrapping_sub(ecx) & 31;
        let s = ((hi | 0xfff0_0000) << 11) | (lo >> 21);
        s >> cl
    } else {
        0
    };
    let mi = esi.wrapping_add(esi & 1);
    let half = esi.wrapping_add(1) >> 1;
    let q = (1u32.wrapping_sub(2 * r8)).wrapping_mul(half) & 3;
    let m = (mi as i32) as f64;
    let (xh, xl);
    if edx < 0x416 {
        let x1 = f(CW_S[0]) * m;
        let x2 = f(CW_S[1]) * m;
        let mut x0 = a - x1;
        let mut x4 = x0;
        let x3 = f(CW_S[2]) * m;
        x4 -= x2;
        x0 -= x4;
        let x7 = m * f(CW_S[3]);
        x0 -= x2;
        let mut y2 = x4;
        y2 -= x3;
        x4 -= y2;
        x4 -= x3;
        x0 += x4;
        x0 -= x7;
        xh = y2;
        xl = x0;
    } else {
        let x1 = f(CW_B[0]) * m;
        let x2 = f(CW_B[1]) * m;
        let mut x0 = a - x1;
        let mut x4 = x0;
        let x3 = f(CW_B[2]) * m;
        x4 -= x2;
        x0 -= x4;
        let mut x8 = x4;
        x0 -= x2;
        x8 -= x3;
        let mut x5 = x8;
        x4 -= x8;
        let x6 = f(CW_B[4]);
        x4 -= x3;
        x0 += x4;
        x5 += x0;
        let mut y2 = x5;
        x8 -= x5;
        x8 += x0;
        let mut z0 = f(CW_B[3]);
        z0 *= m;
        let x7 = m * x6;
        y2 -= z0;
        x5 -= y2;
        x5 -= z0;
        x8 += x5;
        x8 -= x7;
        xh = y2;
        xl = x8;
    }
    let (h, l) = finish_sign(xh, xl, r8);
    (h, l, q, true, None)
}

fn finish_sign(hi: f64, lo: f64, r8: u32) -> (f64, f64) {
    let s = f(SIGN_TAB[r8 as usize]);
    let h2 = hi * s;
    let l2 = lo * s;
    let o = h2 + l2;
    let lo_out = (h2 - o) + l2;
    (o, lo_out)
}

/// |x| >= 2^30, limb product against the 2/pi table .
