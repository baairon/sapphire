/// Table storage: captured entries overlaid on the stand-in.
pub struct Tables {
    pub s: [[u64; 2]; 64],
    pub d: [[u64; 8]; 64],
}

fn parse_hex(s: &str) -> u64 {
    u64::from_str_radix(s, 16).expect("hex word")
}

fn build_tables() -> Tables {
    let mut t = Tables { s: [[0; 2]; 64], d: [[0; 8]; 64] };
    for ln in STAB_TXT.lines().filter(|l| !l.trim().is_empty()) {
        let w: Vec<&str> = ln.split_whitespace().collect();
        let k: usize = w[0].parse().unwrap();
        t.s[k] = [parse_hex(w[1]), parse_hex(w[2])];
    }
    for ln in DTAB_TXT.lines().filter(|l| !l.trim().is_empty()) {
        let w: Vec<&str> = ln.split_whitespace().collect();
        let k: usize = w[0].parse().unwrap();
        for j in 0..8 {
            t.d[k][j] = parse_hex(w[1 + j]);
        }
    }
    for k in 0..16 {
        t.s[k] = CAP_STAB[k];
    }
    for k in 0..4 {
        t.d[k] = CAP_DTAB[k];
    }
    t
}

/// The two tables (captured entries plus labelled stand-in), built once.
pub fn tables() -> &'static Tables {
    static T: OnceLock<Tables> = OnceLock::new();
    T.get_or_init(build_tables)
}

/// Stand-in only (no captured overlay), for the T1 agreement checks.
pub fn standin_tables() -> Tables {
    let mut t = Tables { s: [[0; 2]; 64], d: [[0; 8]; 64] };
    for ln in STAB_TXT.lines().filter(|l| !l.trim().is_empty()) {
        let w: Vec<&str> = ln.split_whitespace().collect();
        let k: usize = w[0].parse().unwrap();
        t.s[k] = [parse_hex(w[1]), parse_hex(w[2])];
    }
    for ln in DTAB_TXT.lines().filter(|l| !l.trim().is_empty()) {
        let w: Vec<&str> = ln.split_whitespace().collect();
        let k: usize = w[0].parse().unwrap();
        for j in 0..8 {
            t.d[k][j] = parse_hex(w[1 + j]);
        }
    }
    t
}

