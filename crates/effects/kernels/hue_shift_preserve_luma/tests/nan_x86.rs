fn run(colour: [f32; 3], shift: f32, n: i32) -> Vec<[u32; 3]> {
    let p = Params { plane_count: 3, flag: false, const_colour: true, colour, scalar_shift: true, shift, n };
    let mut outs = [vec![0.0f32; n as usize], vec![0.0; n as usize], vec![0.0; n as usize]];
    render(&p, None, None, &mut outs).unwrap();
    (0..n as usize).map(|i| [outs[0][i].to_bits(), outs[1][i].to_bits(), outs[2][i].to_bits()]).collect()
}

#[test]
fn fresh_nan_words_are_the_x86_words() {
    let inf = f32::INFINITY;
    let mut got: Vec<u32> = Vec::new();
    // one pixel (scalar loop), five (scalar and 4 wide loops) and eight (wide loop)
    for n in [1, 5, 8] {
        for (c, s) in [([0.5, 0.25, 0.75], inf), ([0.5, 0.25, 0.75], -inf), ([inf, 0.25, -inf], 0.1), ([-inf, 0.5, 0.25], 0.3), ([0.0, 0.0, inf], 0.2)] {
            let r = run(c, s, n);
            for px in r {
                got.extend(px);
            }
        }
    }
    assert_eq!(format!("{got:08x?}"), format!("{EXPECT:08x?}"));
}
