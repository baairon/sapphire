    # ---- table blocks -------------------------------------------------
    def blocks(self):
        d, total = self.d, self.f["code_bytes"]["value"]
        b = OrderedDict()
        tiers = Counter(r["tier"] for r in d.fm)
        rows = []
        for t in TIER_ORDER:
            rs = [r for r in d.fm if r["tier"] == t]
            by = sum(int(r["size"]) for r in rs)
            part = [r for r in rs if r["status"] == "partial"]
            rows.append([t, fmt_int(tiers[t]), fmt_int(by), fmt_pct(by, total), fmt_int(len(part))])
        b["tiers"] = table(["tier", "functions", "bytes", "share of code", "of which partial"], rows)
        rows = []
        for k, label in STRICT_LABEL.items():
            rs = [r for r in d.fm if r["strict"] == k]
            by = sum(int(r["size"]) for r in rs)
            rows.append([label, fmt_int(len(rs)), fmt_int(by), fmt_pct(by, total)])
        rows.insert(2, ["**strict total**", self.t("strict_fns"), self.t("strict_bytes"), self.t("strict_pct")])
        b["strict"] = table(["measure", "functions", "bytes", "share of code"], rows)
        rows = []
        for k, label in EVIDENCE_LABEL.items():
            rs = [r for r in d.fm if r["evidence"] == k]
            by = sum(int(r["size"]) for r in rs)
            rows.append([code(k), label, fmt_int(len(rs)), fmt_int(by), fmt_pct(by, total)])
        b["evidence"] = table(["evidence", "meaning", "functions", "bytes", "share of code"], rows)
        rows = [[code(r["bank_name"]), r["id"], r["offset"], fmt_int(r["size"]), r["tier"], r["status"], r["origin"],
                 code(r["source"] + (":{}".format(r["line"]) if r["line"] else ""))]
                for r in d.rows if r["strict"] == "unproven"]
        b["unproven"] = table(["bank name", "id", "offset", "bytes", "tier", "status", "origin", "source"], rows)
        kinds = ["method", "std", "function", "destructor", "constructor", "initialiser"]
        cnt = Counter((r["origin"], r["kind"]) for r in d.names.values())
        rows = []
        for o in ["bundled_library", "std", "undetermined", "component"]:
            rows.append([o] + [fmt_int(cnt[(o, k)]) for k in kinds] + [fmt_int(sum(cnt[(o, k)] for k in kinds))])
        b["origins"] = table(["origin"] + kinds + ["total"], rows)
        vc = Counter((r["verdict"], r["confidence"]) for r in d.nc.values())
        rows = [[v] + [fmt_int(vc[(v, c)]) for c in ("high", "med", "low")] +
                [fmt_int(sum(vc[(v, c)] for c in ("high", "med", "low")))] for v in ("align", "weak", "mismatch")]
        rows.append(["no verdict", "", "", "", self.t("nc_unchecked")])
        b["namecheck"] = table(["name check", "high", "med", "low", "functions"], rows)
        sc = Counter((r["verdict"], r["confidence"]) for r in d.stubcheck.values())
        rows = [[v] + [fmt_int(sc[(v, c)]) for c in ("high", "med", "low")] +
                [fmt_int(sum(sc[(v, c)] for c in ("high", "med", "low")))] for v in ("align", "weak", "mismatch")]
        b["stubcheck"] = table(["name check", "high", "med", "low", "stubs"], rows)
        hy = Counter(r["outcome"] for r in d.stubhyp.values())
        b["stub_hypotheses"] = table(["role hypothesis", "stubs"], [[k, fmt_int(hy[k])] for k in sorted(hy)])
        lv = Counter(r["level"] for r in d.confirmation.values())
        rows = [[k, fmt_int(lv[k]), CONF_MEANING[k]] for k in CONF_LEVELS]
        other = sum(v for k, v in lv.items() if k not in CONF_MEANING)
        if other:
            rows.append(["other", fmt_int(other), "level not in the list above"])
        b["confirmation"] = table(["confirmation", "functions", "meaning"], rows)
        rows = [[code(c), first_sentence(i["role"], 110), fmt_int(i["files"]), fmt_int(len(i["modules"])),
                 fmt_int(i["tests"])] for c, i in d.crates.items()]
        rows.append(["**total**", "", fmt_int(sum(i["files"] for i in d.crates.values())),
                     fmt_int(sum(len(i["modules"]) for i in d.crates.values())), self.t("tests_scan_total")])
        b["crates"] = table(["crate", "role (first `//!` sentence)", ".rs files", "files with a `//!` header",
                             "`#[test]` lines (scan)"], rows)
        rows = []
        for t in TIER_ORDER:
            done = [r for r in d.fm if r["tier"] == t and r["status"] == "done"]
            part = [r for r in d.fm if r["tier"] == t and r["status"] != "done"]
            db, pb = sum(int(r["size"]) for r in done), sum(int(r["size"]) for r in part)
            rows.append([t, fmt_int(len(done)), fmt_int(db), fmt_pct(db, total), fmt_int(len(part)), fmt_int(pb)])
        b["parity_tiers"] = table(["tier", "done functions", "done bytes", "share of code", "partial functions",
                                   "partial bytes"], rows)
        verdict = {r["symbol"]: r["verdict"] for r in d.audit_final}
        rows = [[code(r["bank_name"]), r["id"], r["offset"], fmt_int(r["size"]), verdict.get(r["id"], "none")]
                for r in d.rows if r["evidence"] == "anyworld"]
        b["anyworld"] = table(["bank name", "id", "offset", "bytes", "audit verdict"], rows)
        per_crate = Counter()
        crate_bytes = Counter()
        for r in d.fm:
            c = r["source"].split("/")[1] if r["source"].startswith("crates/") else ""
            per_crate[c] += 1
            crate_bytes[c] += int(r["size"])
        b["lift_crates"] = table(["crate", "functions", "bytes"], [[code(c), fmt_int(per_crate[c]),
                                                                    fmt_int(crate_bytes[c])] for c in sorted(per_crate)])
        av = Counter(r["verdict"] for r in d.audit_final)
        b["audit_verdicts"] = table(["verdict", "rows"], [[k, fmt_int(v)] for k, v in sorted(av.items())])
        org = Counter(r["origin"] for r in d.names.values())
        b["name_origins"] = table(["origin", "functions"], [[k, fmt_int(v)] for k, v in org.most_common()])
        kd = Counter(r["kind"] for r in d.names.values())
        b["name_kinds"] = table(["kind", "functions"], [[k, fmt_int(v)] for k, v in kd.most_common()])
        so = Counter(r["library_or_origin"] for r in d.stubs)
        b["stub_origins"] = table(["library or origin", "stubs"], [[code(k), fmt_int(v)] for k, v in so.most_common()])
        b["missing"] = [l for l in d.missing_md.split("\n") if l.startswith("|")]
        rows = [[code("docs/data/" + r["path"]), fmt_int(int(r["bytes"])), code(r["sha256"][:16])] for r in d.manifest]
        b["data_files"] = table(["file", "bytes", "sha256 (first 16)"], rows)
        return b

    # ---- generated pages ----------------------------------------------
    def _paged(self, prefix, title_fn, intro, header, rows, keys, by_offset=True, width=6, first_intro=None):
        """Split table rows into pages of at most PAGE_LIMIT bytes; `first_intro` replaces `intro` on page 1."""
        first_intro = first_intro or intro
        pages, cur, cur_keys = [], [], []
        budget = PAGE_LIMIT - max(len("\n".join([DO_NOT_EDIT] + i).encode()) for i in (intro, first_intro)) - 600
        size = 0
        for row, key in zip(rows, keys):
            n = len(row.encode()) + 1
            if cur and size + n > budget:
                pages.append((cur, cur_keys))
                cur, cur_keys, size = [], [], 0
            cur.append(row)
            cur_keys.append(key)
            size += n
        if cur:
            pages.append((cur, cur_keys))
        names = []
        for i, (_, ks) in enumerate(pages):
            if len(pages) == 1:
                names.append(prefix + ".md")
            elif by_offset:
                names.append("{}-0x{:0{w}x}.md".format(prefix, ks[0], w=width))
            else:
                names.append("{}-{}.md".format(prefix, i + 1))
        out = OrderedDict()
        done = 0
        for i, (rs, ks) in enumerate(pages):
            nav = ["[index](index.md)"]
            if i > 0:
                nav.insert(0, "[previous](" + names[i - 1] + ")")
            if i + 1 < len(pages):
                nav.append("[next](" + names[i + 1] + ")")
            first, last = done + 1, done + len(rs)
            done = last
            body = [DO_NOT_EDIT, "# " + title_fn(ks[0], ks[-1], len(pages) > 1), "",
                    "Rows {} to {} of {}. Pages: {}.".format(fmt_int(first), fmt_int(last), fmt_int(len(rows)),
                                                            " ".join(nav)), ""]
            body += (first_intro if i == 0 else intro) + [""] + header + rs + [""]
            out[GEN_DIR + "/" + names[i]] = "\n".join(body)
        return out

    def page_functions(self, stubs_page):
        f = self.f
        what = ("Every function of the dump in offset order, bank name first with the id beside it; the code symbols "
                "stay `f_XXXXXXXX`. One function: `python -I tools/fn_info.py ID|NAME|OFFSET`.")
        columns = ("Columns: \"name check\" is the merged verdict and confidence of the name check tables; "
                   "\"confirmation\" is the level in `docs/data/name_confirmation.tsv`; \"callers\" and \"stubs\" give "
                   "a count, then at most three callers or import stub offsets ([stubs]({})); \"source\" is the file "
                   "and line of the Rust definition.".format(stubs_page))
        caveat = ("Bank names come from the name bank. Argument counts fit the bank signatures for {}% of {} lifted "
                  "functions, against about {}% when every name is shifted by one function.".format(
                      f["arity_fit_pct"]["text"], f["arity_fit_base"]["text"], f["arity_shift_pct"]["text"]))
        intro = [what, "", columns]
        header = table(["offset", "bank name", "id", "kind", "origin", "class", "size", "tier", "evidence",
                        "strict", "name check", "confirmation", "callers", "stubs", "source"], [])
        rows, keys = [], []
        for r in self.d.rows:
            src = r["source"] + (":{}".format(r["line"]) if r["line"] else "")
            rows.append("| " + " | ".join([
                r["offset"], code(r["bank_name"]), r["id"], r["kind"], r["origin"], code(r["class"]) if r["class"] else "",
                fmt_int(r["size"]), r["tier"], r["evidence"], r["strict"], r["name_check"], r["confirmation"],
                short_list(r["callers"]), short_list(r["stubs"]), code(src)]) + " |")
            keys.append(int(r["offset"], 16))
        title = lambda a, b, many: "Functions 0x{:x} to 0x{:x}".format(a, b) if many else "Functions"
        return self._paged("functions", title, intro, header, rows, keys,
                           first_intro=[what, "", caveat, "", columns])

    def page_stubs(self):
        d = self.d
        intro = ["The {} import stubs the dump calls: call targets outside the dump, each named by the bank.".format(
            self.t("stubs_total"))]
        header = table(["stub offset", "bank name", "library or origin", "name check", "role hypothesis",
                        "calling functions"], [])
        rows, keys = [], []
        for s in d.stubs:
            off = s["stub_rel_off"]
            ck = d.stubcheck.get(off)
            hy = d.stubhyp.get(off, {}).get("outcome", "")
            rows.append("| " + " | ".join([off, code(s["exact_target"]), code(s["library_or_origin"]),
                                           "{} {}".format(ck["verdict"], ck["confidence"]) if ck else "none",
                                           hy, fmt_int(d.stub_callers.get(int(off, 16), 0))]) + " |")
            keys.append(int(off, 16))
        title = lambda a, b, many: "Stubs 0x{:x} to 0x{:x}".format(a, b) if many else "Stubs"
        return self._paged("stubs", title, intro, header, rows, keys, width=4)

    def _strings(self, path, title, values, what):
        """A verbatim list: one bank string per line inside a fenced block, in bank order."""
        body = [DO_NOT_EDIT, "# " + title, "", what, "", "```text"] + list(values) + ["```", ""]
        return {GEN_DIR + "/" + path: "\n".join(body)}

    def page_effects(self):
        what = ("The {} effect names of the name bank, verbatim and in bank order, one per line. "
                "No effect is mapped to a function, a class, a parameter or a behaviour.").format(self.t("effects_total"))
        return self._strings("effects.md", "Effect names", [r["name"] for r in self.d.effects], what)

    def page_params(self):
        what = ("The {} parameter candidates of the name bank, verbatim and in bank order, one per line: strings found in "
                "the build it replaces, bound to no function or effect, and not confirmed parameters.").format(
                    self.t("params_total"))
        return self._strings("parameters.md", "Parameter candidates", [r["candidate"] for r in self.d.params], what)

    def page_classes(self):
        d = self.d
        rows = []
        for c in d.classes:
            n = c["class_name"]
            fns = [r for r in d.rows if r["class"] == n]
            rows.append([code(n), code(c["base_class"]) if c["base_class"] else "", c["vtable_offset"],
                         fmt_int(len(fns)), fmt_int(sum(r["kind"] == "constructor" for r in fns)),
                         fmt_int(sum(r["kind"] == "destructor" for r in fns)), code(c["mangled_vtable"])])
        body = [DO_NOT_EDIT, "# Classes", "",
                "The {} local classes of the name bank with their base classes; all {} hierarchies match the "
                "structure inferred from the code, and {} of the constructors and destructors that reference a local "
                "vtable reference their own class.".format(
                    self.t("classes_total"), self.t("class_hier_match"), self.t("ctor_dtor_own_vtable")), ""]
        body += table(["class", "base class", "vtable offset", "functions", "constructors", "destructors",
                       "mangled vtable"], rows) + [""]
        return {GEN_DIR + "/classes.md": "\n".join(body)}

